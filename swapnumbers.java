package javabasics;

public class swapnumbers 
{
	public static void main(String[] args) 
	{
		
		int a=50;
		
		int b=100;
		
		
		a= a+b;     //  a becomes 100+50 =150
		
		b=a-b;       //  b becomes 150-100=50
				
		a= a-b;      //  a becomes 150-50=100 
		
		
		System.out.println(a+ " "+ b);

		
		
		 
		
	}

}
